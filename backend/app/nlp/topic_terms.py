def all_terms() -> dict[str, float]:
    """Flatten the gazetteer for a single matcher pass.

    Returns a term -> weight map. Where a term appears under several topics the
    highest weight wins; per-topic attribution is recovered from
    :data:`TOPIC_TERMS` during scoring.
    """
    flattened: dict[str, float] = {}
    for terms in TOPIC_TERMS.values():
        for term, weight in terms.items():
            flattened[term] = max(flattened.get(term, 0.0), weight)
    return flattened


def topics_for_term(term: str) -> list[tuple[str, float]]:
    """Every topic a term signals, with that topic's weight for it."""
    return [
        (topic, terms[term]) for topic, terms in TOPIC_TERMS.items() if term in terms
    ]


def gazetteer_size() -> dict[str, int]:
    """Term count per topic, reported by the API for transparency."""
    return {topic: len(terms) for topic, terms in TOPIC_TERMS.items()}
